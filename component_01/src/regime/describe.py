"""M3 - What each regime name actually means in each trained model.

Run:  python -m src.regime.describe      (writes docs/REGIME_DEFINITIONS.md)

WHY this exists. The four regime names are assigned to anonymous HMM states by
one fixed rule (src/regime/state_mapping.py). Each asset and timeframe has its
own independent model, so the state that receives a given name is not
identical everywhere. In particular the state named "Volatile" is the more
active of the two non-directional states; it is not always the most volatile
state of its model. This module turns the saved training-period profiles into
a table, so the meaning of every label is stated rather than assumed.

Nothing is fitted or changed here. It only reads results/*_hmm_report.json.
"""
import json

import numpy as np
import pandas as pd

from src import config

DOCS_DIR = config.ROOT_DIR / "docs"


def load_profiles(symbol: str, interval: str) -> dict[str, dict] | None:
    """Training-period profile of each regime of one model, or None if the
    model report does not exist.

    volatility_vs_norm is exp(atr_rel): the typical price range in that
    regime as a multiple of its own past-year norm (1.0 = normal, 2.0 = twice).
    """
    path = config.RESULTS_DIR / f"{symbol}_{interval}_hmm_report.json"
    if not path.exists():
        return None
    with open(path) as file:
        states = json.load(file)["state_profiles"].values()
    most_volatile = max(states, key=lambda state: state["atr_rel"])["regime"]
    return {state["regime"]: {
        "typical_rsi": round(state["rsi"], 1),
        "volatility_vs_norm": round(float(np.exp(state["atr_rel"])), 2),
        "share_of_training_time": round(state["share"], 3),
        "is_most_volatile_state": state["regime"] == most_volatile,
    } for state in states}


def profile_table() -> pd.DataFrame:
    """One row per model and regime."""
    rows = []
    for symbol in config.SYMBOLS:
        for interval in config.INTERVALS:
            profiles = load_profiles(symbol, interval)
            for regime in config.REGIMES:
                rows.append({"asset": symbol, "timeframe": interval, "regime": regime,
                             **profiles[regime]})
    return pd.DataFrame(rows)


def write_definitions() -> pd.DataFrame:
    table = profile_table()
    volatile = table[table["regime"] == "Volatile"]
    truly = int(volatile["is_most_volatile_state"].sum())

    lines = [
        "# What the four regime names mean",
        "",
        "*Generated by `python -m src.regime.describe` from the saved model reports. "
        "Do not edit by hand.*",
        "",
        "## Definitions",
        "",
        "Each model has four states. The names are given by one fixed rule, the same for "
        "every asset and timeframe, using each state's average behaviour in the training "
        "period (data up to " + config.TRAIN_END + "):",
        "",
        "| Name | Rule | Plain meaning |",
        "|---|---|---|",
        "| **Bullish** | The state with the highest average RSI | Gains outweigh losses; "
        "price is rising |",
        "| **Bearish** | The state with the lowest average RSI | Losses outweigh gains; "
        "price is falling |",
        "| **Sideways** | Of the two states left, the one with the lower volatility "
        "relative to its past-year norm | No clear direction, quiet |",
        "| **Volatile** | Of the two states left, the one with the higher volatility "
        "relative to its past-year norm | No clear direction, more active than Sideways |",
        "",
        "## What \"Volatile\" does and does not mean",
        "",
        "\"Volatile\" is the **more active of the two non-directional states**. It is not "
        "defined as the most volatile state of the model.",
        "",
        f"- In **{truly} of {len(volatile)} models** the Volatile state is also the most "
        "volatile state of that model.",
        f"- In the other **{len(volatile) - truly}**, the most volatile state is Bearish, "
        "because in those models sharp sell-offs are the most volatile periods. There the "
        "Volatile state is a mild, in-between state with volatility close to normal.",
        "",
        "So the same name can describe a truly turbulent state at one timeframe and a mild "
        "one at another. This follows from giving each timeframe its own independent model. "
        "Use the table below, or the `regime_profile` field of the output record, to see "
        "what a label means for a particular model.",
        "",
        "## Profile of every regime in every model",
        "",
        "- **Typical RSI**: above 50 means gains outweigh losses, below 50 the reverse.",
        "- **Volatility vs norm**: the typical price range in that regime as a multiple of "
        "its own past-year norm. 1.00 is normal, 2.00 is twice the norm, 0.60 is quiet.",
        "- **Share**: share of the training period spent in the regime.",
        "",
        "| Asset | Timeframe | Regime | Typical RSI | Volatility vs norm | Share | "
        "Most volatile state of this model? |",
        "|---|---|---|---|---|---|---|",
    ]
    for row in table.itertuples():
        lines.append(
            f"| {row.asset} | {row.timeframe} | {row.regime} | {row.typical_rsi:.1f} | "
            f"{row.volatility_vs_norm:.2f} | {row.share_of_training_time:.1%} | "
            f"{'yes' if row.is_most_volatile_state else ''} |")
    DOCS_DIR.mkdir(exist_ok=True)
    (DOCS_DIR / "REGIME_DEFINITIONS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return table


def main() -> None:
    table = write_definitions()
    volatile = table[table["regime"] == "Volatile"]
    print(volatile[["asset", "timeframe", "typical_rsi", "volatility_vs_norm",
                    "is_most_volatile_state"]].to_string(index=False))
    print(f"\n'Volatile' is the most volatile state in "
          f"{int(volatile['is_most_volatile_state'].sum())} of {len(volatile)} models.")
    print("Written: docs/REGIME_DEFINITIONS.md")


if __name__ == "__main__":
    main()
